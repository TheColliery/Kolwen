// Tests for the status page (web/status.html, generated from web-src/pages/status.html) and its script (web/status.js). Read-only: nothing here writes web/ or reaches the
// network. Run: node --test scripts/status-page.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = f => readFileSync(join(ROOT, f), 'utf8');

test('the generated status page exists, is unannounced (no link, not in the sitemap) and carries no noindex, which rule 16 refuses on a production page', () => {
  assert.ok(existsSync(join(ROOT, 'web', 'status.html')), 'web/status.html is generated by node scripts/legal-pages.mjs --write');
  const html = read('web/status.html');
  assert.doesNotMatch(html, /<meta name="robots"/);
  assert.doesNotMatch(read('web/sitemap.xml'), /\/status</, 'not in the sitemap while unannounced');
  for (const f of ['web/index.html', 'web/pricing.html', 'web/404.html']) assert.doesNotMatch(read(f), /href="\/status"/, f + ' does not link to it');
});

test('the status page loads nothing from a third-party origin: every script, image, frame and stylesheet is on kolwen.com or relative', () => {
  const html = read('web/status.html');
  const loads = [
    ...html.matchAll(/<(?:script|img|iframe|source|video|audio|embed)[^>]*\ssrc=["']([^"']*)["']/gi),
    ...html.matchAll(/<link[^>]*\shref=["']([^"']*)["']/gi),
  ].map(m => m[1]);
  assert.deepEqual(loads.filter(u => /^(?:https?:)?\/\//.test(u) && !u.startsWith('https://kolwen.com/')), []);
});

test('the status page fetches /status.json and nothing else', () => {
  const html = read('web/status.html');
  assert.match(html, /<main data-status>/, 'the page script finds the status page by this marker');
  const targets = [...html.matchAll(/fetch\(\s*['"]([^'"]*)['"]/g)].map(m => m[1]);
  assert.deepEqual(targets, ['/status.json']);
});

test('the "no check yet" line is in both languages', () => {
  const html = read('web/status.html');
  assert.match(html, /No check has run yet\./, 'English');
  assert.match(html, /ยังไม่มีการตรวจสอบ/, 'Thai');
});
